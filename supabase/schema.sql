create extension if not exists pgcrypto;

create type public.app_role as enum ('elder','family','community','admin');
create type public.risk_level as enum ('red','yellow','green');
create type public.alert_status as enum ('待处理','已处理');

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  phone text,
  role public.app_role not null default 'elder',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.communities (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.community_memberships (
  community_id uuid not null references public.communities(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  approved boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (community_id,user_id)
);

create table if not exists public.elder_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid unique references public.profiles(id) on delete set null,
  name text not null,
  age int check (age between 0 and 120),
  dialect text not null default '',
  living text not null default '',
  family_name text not null default '',
  relation text not null default '',
  community_id uuid references public.communities(id) on delete set null,
  risk_level public.risk_level not null default 'green',
  mood text not null default '平稳',
  screened boolean not null default false,
  last_call timestamptz,
  last_active timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.family_members (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  family_user_id uuid not null references public.profiles(id) on delete cascade,
  relation text not null default '家属',
  approved_by_elder boolean not null default false,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  unique (elder_id,family_user_id)
);
create table if not exists public.consents (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  granted_by uuid not null references public.profiles(id),
  consent_type text not null check (consent_type in ('screening','family_view','community_followup','conversation_summary','risk_alert')),
  granted boolean not null default false,
  recorded_at timestamptz not null default now(),
  revoked_at timestamptz
);

create table if not exists public.assessment_sessions (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  conducted_by uuid references public.profiles(id) on delete set null,
  scale_name text not null default '未指定量表',
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  consent_confirmed boolean not null default false
);
create table if not exists public.assessment_answers (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.assessment_sessions(id) on delete cascade,
  question_key text not null,
  answer jsonb not null,
  created_at timestamptz not null default now()
);
create table if not exists public.assessment_results (
  id bigint generated by default as identity primary key,
  session_id bigint not null unique references public.assessment_sessions(id) on delete cascade,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  risk_level public.risk_level not null,
  score numeric,
  interpretation text not null default '',
  assessed_at timestamptz not null default now(),
  assessed_by uuid references public.profiles(id) on delete set null
);

create table if not exists public.risk_cases (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  risk_level public.risk_level not null default 'green',
  status text not null default 'open' check (status in ('open','monitoring','closed')),
  opened_at timestamptz not null default now(),
  closed_at timestamptz
);
create table if not exists public.risk_events (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  case_id bigint references public.risk_cases(id) on delete set null,
  keyword text not null default '',
  summary text not null default '',
  severity public.risk_level not null default 'red',
  status public.alert_status not null default '待处理',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create table if not exists public.case_actions (
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.risk_events(id) on delete cascade,
  method text not null,
  note text not null default '',
  handler uuid references public.profiles(id) on delete set null,
  handler_name text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.activity_records (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  rounds int not null default 1 check (rounds between 1 and 100),
  duration_min int not null default 0 check (duration_min between 0 and 1440),
  mood text not null default '平稳',
  note text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.conversation_summaries (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  mood text not null default '平稳',
  summary text not null default '',
  turns jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.care_messages (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  sender_user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  conveyed boolean not null default false,
  created_at timestamptz not null default now(),
  conveyed_at timestamptz
);
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elder_profiles(id) on delete cascade,
  target text not null default '乡镇卫生院',
  status text not null default '待跟进',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor uuid references public.profiles(id) on delete set null,
  action text not null,
  resource_type text not null,
  resource_id text,
  created_at timestamptz not null default now()
);

