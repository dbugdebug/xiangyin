-- Signup profile creation. Role is always assigned server-side/default 'elder'; never trust a client-supplied role.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name, phone, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name',''), new.phone, 'elder')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

