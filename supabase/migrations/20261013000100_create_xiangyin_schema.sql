create type public.risk_level as enum ('red', 'yellow', 'green');
create type public.alert_status as enum ('pending', 'processed');
create type public.alert_severity as enum ('high', 'mid');

create table public.elders (
  id bigint generated by default as identity primary key,
  name text not null,
  age integer not null,
  dialect text,
  living text,
  family_name text,
  relation text,
  last_call text,
  phone text,
  language text not null default 'zh-CN',
  risk_level public.risk_level not null default 'green',
  last_active timestamptz,
  mood text,
  mood_summary text,
  screened boolean not null default false,
  created_at timestamptz not null default now()
);
create index elders_risk_idx on public.elders(risk_level);

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('elder', 'family', 'villager')),
  elder_id bigint references public.elders(id) on delete set null,
  created_at timestamptz not null default now()
);

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (user_id, role) values (new.id, 'elder')
  on conflict (user_id) do nothing;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table public.family_relations (
  id bigint generated by default as identity primary key,
  family_user_id uuid not null references auth.users(id) on delete cascade,
  elder_id bigint not null references public.elders(id) on delete cascade,
  relationship text,
  created_at timestamptz not null default now(),
  unique (family_user_id, elder_id)
);

create table public.emotion_records (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elders(id) on delete cascade,
  emotion text not null,
  reason text,
  intensity integer,
  user_message text,
  ai_reply text,
  date date not null default current_date,
  "timestamp" timestamptz not null default now(),
  language text not null default 'zh-CN',
  created_at timestamptz not null default now()
);
create index emotion_records_elder_date_idx on public.emotion_records(elder_id, date);

create table public.activities (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elders(id) on delete cascade,
  date date not null default current_date,
  rounds integer not null default 0,
  duration_min integer not null default 0,
  active_slot text,
  mood integer not null default 0 check (mood between -2 and 2),
  note text,
  created_at timestamptz not null default now(),
  unique (elder_id, date)
);

create table public.alerts (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elders(id) on delete cascade,
  keyword text,
  summary text,
  status public.alert_status not null default 'pending',
  severity public.alert_severity not null default 'mid',
  method text,
  handle_note text,
  handler text,
  processed_at timestamptz,
  created_at timestamptz not null default now()
);
create index alerts_status_idx on public.alerts(status);
create index alerts_elder_idx on public.alerts(elder_id);

create table public.care_messages (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elders(id) on delete cascade,
  content text not null,
  conveyed boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.referrals (
  id bigint generated by default as identity primary key,
  elder_id bigint not null references public.elders(id) on delete cascade,
  target text,
  status text not null default '待跟进' check (status in ('已联系', '随访中', '已完成', '待跟进')),
  created_at timestamptz not null default now()
);

