let genericIndex = 0

function pick(list: string[]): string {
  return list[Math.floor(Math.random() * list.length)]
}

/** 根据老人说的话，挑一条温暖的 mock 回复 */
export function mockReply(userText: string): string {
  const hit = RULES.find((r) => r.keys.some((k) => userText.includes(k)))
  if (hit) return pick(hit.replies)
  const reply = GENERIC[genericIndex % GENERIC.length]
  genericIndex += 1
  return reply
}
